/**
 * Как записать ответ — подсказка ученику под полем ввода.
 *
 * Правило генерации: в конце задания с вводом написано, как записать ответ
 * («Ответ запишите целым числом.», «…одним словом в именительном падеже.»).
 * Эту фразу и показываем под полем — ученик не гадает, писать ли «∞»,
 * слово или промежуток. Нет такой фразы — null, и страница покажет общую подсказку.
 * То же правило распознавания — на сервере (FORMAT_HINT_RE в ai_generation.py).
 */

const FORMAT_HINT =
  /(ответ|запишите|введите|укажите|напишите)[^.?!]*(числ|дроб|слов|цифр|падеж|букв|год|через\s+запят|целым|десятичн|градус|единиц|сантиметр|метр|грамм|литр|секунд|рубл|процент|форм[еуы]|в\s+виде|латиниц|английск)/i

export function answerFormatHint(text: string): string | null {
  // Формулы не режем по точкам внутри них: «$2.5$» — не конец предложения.
  const sentences = text
    .replace(/\$[^$]*\$/g, (formula) => formula.replace(/[.?!]/g, '․'))
    .split(/(?<=[.?!])\s+/)
    .map((sentence) => sentence.trim())
    .filter((sentence) => sentence !== '')

  for (let index = sentences.length - 1; index >= 0; index -= 1) {
    const sentence = sentences[index]
    if (FORMAT_HINT.test(sentence)) {
      return sentence.replace(/․/g, '.')
    }
  }
  return null
}
