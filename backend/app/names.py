"""
Нормализация ФИО ученика.

Зачем: ученик пишет имя от руки на телефоне. «радов  мадлена», «РАДОВ МАДЛЕНА»
и «Радов Мадлена» — это один человек, и в списке у учителя они должны стоять
одной строкой. Кроме того, на нормализованном имени держится защита от
пересдачи: без неё достаточно сменить регистр, чтобы сдать работу второй раз.

Правила:
  * пробелы по краям убираются, двойные внутри схлопываются;
  * каждое слово с заглавной буквы, остальные буквы строчные;
  * части через дефис и инициалы тоже с заглавной:
    «петров-водкин» → «Петров-Водкин», «иванов и.и.» → «Иванов И.И.».
"""

import re

# Группа букв (юникодная): [^\W\d_] — «не не-буква, не цифра, не подчёркивание».
# Так мы находим именно слова, не перечисляя алфавиты, и не трогаем дефисы с точками.
LETTERS = re.compile(r"[^\W\d_]+", re.UNICODE)


def normalize_full_name(raw: str) -> str:
    """Приводит ФИО к единому виду. Пустую строку возвращает как есть."""
    # split() без аргументов делит по любым пробелам и отбрасывает пустые части.
    collapsed = " ".join(raw.split())

    # Каждую группу букв делаем «Слово»: работает и для дефисов («Петров-Водкин»),
    # и для инициалов («Иванов И.И.»).
    return LETTERS.sub(lambda match: match.group(0).capitalize(), collapsed)


def normalize_class_name(raw: str) -> str:
    """
    Класс приводим мягче: только пробелы.

    Регистр не меняем — класс ученик выбирает из списка, заданного учителем,
    и написание там уже правильное («6А», «10-Б», «5 инж»).
    """
    return " ".join(raw.split())


def name_key(full_name: str) -> str:
    """
    ФИО для сравнения «тот же ли это ученик»: регистр и «ё/е» не важны.

    На этом ключе держится правило «один ученик — одна попытка в классе»:
    «Алёна Ёжикова» и «алена ежикова» — один человек.
    """
    return normalize_full_name(full_name).lower().replace("ё", "е")
