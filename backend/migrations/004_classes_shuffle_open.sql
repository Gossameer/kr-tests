-- =====================================================================
-- Миграция 004: настройки контрольной, защита от пересдачи, каскадное удаление.
--
-- Накат:  psql -U postgres -d kr_tests -f migrations/004_classes_shuffle_open.sql
-- Откат:  psql -U postgres -d kr_tests -f migrations/004_classes_shuffle_open.down.sql
--
-- Что добавляется:
--   tests.classes   — список классов, из которого ученик выбирает свой
--   tests.shuffle   — перемешивать ли вопросы и варианты у каждого ученика
--   tests.is_open   — открыт ли приём работ
--   attempts.test_id ON DELETE CASCADE — чтобы контрольную можно было удалить
--   уникальность (test_id, student_name, student_class) — одна работа на ученика
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Настройки контрольной
-- ---------------------------------------------------------------------

-- TEXT[] — массив строк. Для списка классов это проще отдельной таблицы:
-- классы нужны только внутри одной контрольной и не связаны ни с чем ещё.
-- DEFAULT '{}' = пустой массив, чтобы старые контрольные не нарушали NOT NULL.
ALTER TABLE tests
    ADD COLUMN IF NOT EXISTS classes TEXT[] NOT NULL DEFAULT '{}';

-- Перемешивание по умолчанию включено: так списывать у соседа бессмысленно.
ALTER TABLE tests
    ADD COLUMN IF NOT EXISTS shuffle BOOLEAN NOT NULL DEFAULT TRUE;

-- Приём работ по умолчанию открыт.
ALTER TABLE tests
    ADD COLUMN IF NOT EXISTS is_open BOOLEAN NOT NULL DEFAULT TRUE;

-- ---------------------------------------------------------------------
-- 2. Каскадное удаление попыток вместе с контрольной
--
-- В 001_init внешний ключ был без каскада — намеренно, чтобы нельзя было
-- случайно снести контрольную с результатами. Теперь удаление стало
-- отдельным осознанным действием (учитель подтверждает его вводом названия),
-- поэтому каскад уместен: иначе пришлось бы удалять работы вручную.
-- ---------------------------------------------------------------------
ALTER TABLE attempts
    DROP CONSTRAINT IF EXISTS attempts_test_id_fkey;

ALTER TABLE attempts
    ADD CONSTRAINT attempts_test_id_fkey
    FOREIGN KEY (test_id) REFERENCES tests (id) ON DELETE CASCADE;

-- ---------------------------------------------------------------------
-- 3. Одна работа на ученика в рамках одной контрольной
--
-- ФИО с этого момента нормализуется на сервере («радов  мадлена» →
-- «Радов Мадлена»), поэтому регистр и лишние пробелы больше не позволяют
-- сдать работу второй раз.
--
-- ВАЖНО: работы, сданные ДО этой миграции, остаются как есть — их написание
-- не меняется, иначе два варианта одного имени слились бы в один и строку
-- пришлось бы удалять. Если индекс не создастся из-за уже существующих
-- дублей, найдите их так:
--
--   SELECT test_id, student_name, student_class, count(*)
--   FROM attempts
--   GROUP BY test_id, student_name, student_class
--   HAVING count(*) > 1;
--
-- и удалите лишние строки вручную, затем повторите накат.
-- ---------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS uq_attempts_test_student
    ON attempts (test_id, student_name, student_class);

COMMIT;
